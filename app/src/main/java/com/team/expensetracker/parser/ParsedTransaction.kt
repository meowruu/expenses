package com.team.expensetracker.parser

import com.team.expensetracker.data.model.Transaction
import com.team.expensetracker.data.model.TransactionType

/**
 * Represents a structured candidate transaction successfully parsed from an SMS message.
 *
 * Privacy Invariants:
 * - Stores strictly normalized, structured financial fields.
 * - Under NO circumstances does this class store, reference, or leak raw SMS text.
 * - Money is represented strictly as [amountPaise] in [Long] to eliminate floating-point rounding errors.
 *
 * Separation of Concerns:
 * This data class models the output of the parsing phase. Fields that belong to downstream
 * layers (such as categorization, database autogenerated ID, and user-owned UPI deduplication)
 * are cleanly populated by downstream components or via [toTransaction].
 *
 * @property amountPaise Transaction amount in paise (1 INR = 100 paise). Long, never Float or Double.
 * @property type The transaction direction ([TransactionType.DEBIT] or [TransactionType.CREDIT]).
 * @property merchant The name of the merchant, payee, or counterparty (nullable).
 * @property upiId The UPI ID associated with the transaction (nullable, e.g. "merchant@bank").
 * @property refNumber Bank reference number / UTR for transaction deduplication (nullable).
 * @property date Epoch timestamp in milliseconds when the SMS was received.
 * @property bank The issuing bank name or sender identifier (e.g., "AXISBK", "HDFC", "SBI").
 * @property accountLastDigits Masked account or card last digits if extracted (e.g. "XX1234").
 */
data class ParsedTransaction(
    val amountPaise: Long,
    val type: TransactionType,
    val merchant: String?,
    val upiId: String?,
    val refNumber: String?,
    val date: Long,
    val bank: String,
    val accountLastDigits: String? = null
) {
    /**
     * Converts this parsed transaction candidate into the core domain [Transaction] entity.
     *
     * @param category The expense category assigned by downstream categorizer (e.g. B1 Categorizer).
     * @param id The persistent entity ID (defaults to 0L for unpersisted entities).
     * @return A domain [Transaction] ready for Room persistence via [com.team.expensetracker.data.repository.TransactionRepository].
     */
    fun toTransaction(category: String = "Uncategorized", id: Long = 0L): Transaction {
        return Transaction(
            id = id,
            amountPaise = amountPaise,
            type = type,
            merchant = merchant,
            upiId = upiId,
            refNumber = refNumber,
            date = date,
            bank = bank,
            category = category
        )
    }
}
