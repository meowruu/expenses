package com.team.expensetracker.data.model

/**
 * Represents a parsed financial transaction.
 *
 * Privacy Rule Compliance:
 * Per project specifications and RULES.md, this data model strictly stores only parsed,
 * structured financial attributes. Under NO circumstances should raw SMS text or any
 * unparsed message contents be stored in this class or persisted anywhere in the system.
 *
 * Amount Representation:
 * The [amountPaise] field represents the amount in paise (1 INR = 100 paise) as an integer [Long].
 * Never use Float or Double to guarantee zero floating-point rounding errors.
 *
 * Deduplication:
 * The [refNumber] field represents the bank reference / UTR number and is used by the repository
 * to deduplicate incoming transactions.
 *
 * @property id Unique identifier for the transaction (0L indicates an unpersisted entity with an autogenerated ID).
 * @property amountPaise Transaction amount in paise (1 INR = 100 paise). Must be a Long, never Float or Double.
 * @property type The transaction direction ([TransactionType.DEBIT] or [TransactionType.CREDIT]).
 * @property merchant The name of the merchant, payee, or counterparty (nullable).
 * @property upiId The UPI ID associated with the transaction (nullable, e.g. "merchant@bank").
 * @property refNumber Bank reference number / UTR for transaction deduplication (nullable).
 * @property date Epoch timestamp in milliseconds when the transaction occurred.
 * @property bank The issuing bank name or sender identifier (e.g., "HDFC", "SBI", "AXISBK").
 * @property category The assigned expense category (e.g., "Food", "Shopping", "Bills").
 */
data class Transaction(
    val id: Long = 0L,
    val amountPaise: Long,
    val type: TransactionType,
    val merchant: String?,
    val upiId: String?,
    val refNumber: String?,
    val date: Long,
    val bank: String,
    val category: String
)
